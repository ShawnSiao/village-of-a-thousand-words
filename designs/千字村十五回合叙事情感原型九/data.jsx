function getPledgeState(storyId, variantId, directAnswers) {
  const answer = directAnswers && directAnswers[storyId];
  const accepted = answer === "accept" || Boolean(answer && answer.pledge === "accept");
  if (!accepted || !["E05", "E08", "E10", "E12"].includes(storyId)) return null;
  const descriptions = {
    E05: "祝婆托付：请让后来者知道，千字村的先祖也曾是外来者。",
    E08: "祝婆托付：七个名字若放不下，至少让夷光留下。",
    E10: "祁生托付：无论假片留下还是磨去，都写清不是祁生伪造。",
    E12: "小满托付：让下一任守字人知道，千字碑曾被改写，也可能继续被改写。"
  };
  if (!variantId) return {
    state: "等待定稿",
    tone: "pending",
    detail: descriptions[storyId]
  };
  const kept = variantId === "full" || (storyId === "E05" && variantId === "principle") || (storyId === "E08" && variantId === "one_name");
  if (kept) return {
    state: "红线完整",
    tone: "kept",
    detail: storyId === "E08" && variantId === "one_name"
      ? "夷光的姓名被保留，托付的最低要求已经兑现。"
      : storyId === "E05" && variantId === "principle"
        ? "先祖也曾是外来者仍在，但七名接纳者被压缩成一项原则。"
        : "托付要求的事实已经明确进入本年碑文。"
  };
  return {
    state: "红线断裂",
    tone: "broken",
    detail: descriptions[storyId] + " 当前版本没有保留这项已经接受的要求。"
  };
}

